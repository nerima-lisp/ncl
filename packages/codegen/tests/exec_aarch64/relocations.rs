use super::*;
use ncl_codegen::{Relocation, RelocationError, RelocationKind};

#[test]
fn rejects_injected_relocation_crossing_generated_aarch64_code_boundary() {
    let mut builder = FunctionBuilder::new(
        ncl_ir::FunctionId(120),
        "relocation-boundary",
        Vec::new(),
        Vec::new(),
    );
    builder
        .terminate(Terminator::Return { values: Vec::new() })
        .expect("return");

    let compiled = compile_function_aarch64(&builder.finish(), &Aarch64Abi).expect("lowering");
    let original = compiled.code;
    let mut bytes = original.clone();
    let offset = u32::try_from(bytes.len().checked_sub(4).expect("return instruction"))
        .expect("generated code offset fits u32");
    // This malformed relocation is injected into generated bytes; it is not compiler output.
    let relocation = Relocation {
        offset,
        kind: RelocationKind::Absolute64,
        target: ncl_asm_x86_64::Label(0),
        addend: 0,
    };

    assert_eq!(
        relocation.apply_to_bytes(&mut bytes, 0, 0),
        Err(RelocationError::PatchOutOfBounds {
            offset,
            width: 8,
            length: original.len(),
        })
    );
    assert_eq!(bytes, original);
}
