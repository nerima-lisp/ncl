use super::*;
use ncl_asm_x86_64::Label;
use ncl_codegen::{Relocation, RelocationError, RelocationKind};

#[test]
fn rejects_injected_relocation_crossing_generated_code_boundary_without_mutation() {
    let mut builder = FunctionBuilder::new(
        ncl_ir::FunctionId(110),
        "relocation-boundary",
        Vec::new(),
        vec![Ty::Word],
    );
    let constant = builder.add_constant(ncl_ir::Constant::T);
    let value = builder
        .push_op(OpKind::Const { result: constant }, &[Ty::Word])
        .expect("constant")[0];
    builder
        .terminate(Terminator::Return {
            values: vec![value],
        })
        .expect("return");

    let compiled = compile_function_x86_64(&builder.finish(), &X86_64Abi).expect("compile");
    assert!(
        compiled.code.len() >= 3,
        "generated function has patch span"
    );

    let original = compiled.code;
    let mut bytes = original.clone();
    let offset = u32::try_from(bytes.len() - 3).expect("code offset fits u32");
    // This malformed negative case is injected into generated bytes, not emitted by the backend.
    let injected_relocation = Relocation {
        offset,
        kind: RelocationKind::PcRelative32,
        target: Label(0),
        addend: 0,
    };

    assert_eq!(
        injected_relocation.apply_to_bytes(&mut bytes, 0, 0),
        Err(RelocationError::PatchOutOfBounds {
            offset,
            width: 4,
            length: original.len(),
        })
    );
    assert_eq!(bytes, original);
}
