pub(in crate::evaluator) fn is_special_form(form: &Form) -> bool {
    atom_name(form).is_some_and(|operator| {
        SPECIAL_FORM_NAMES
            .iter()
            .any(|name| name.eq_ignore_ascii_case(operator))
    })
}
